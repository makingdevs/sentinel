visitor_integer = fn name, default, range ->
  case Integer.parse(System.get_env(name, to_string(default))) do
    {value, ""} ->
      if value in range, do: value, else: raise("#{name} outside permitted range")

    _ ->
      raise "#{name} must be an integer"
  end
end

